"""Static learning catalogue: what each concept means, its level, and free official resources.

Resources are hand-picked official documentation and well-known free guides, so links are
stable and trustworthy (no live web search, nothing generated by an LLM).
"""

from pydantic import BaseModel


class Resource(BaseModel):
    title: str
    url: str
    kind: str  # docs | guide | reference


class ConceptInfo(BaseModel):
    level: int  # 1 fundamentals, 2 core, 3 advanced: the order of the learning pathway
    description: str
    resources: list[Resource]


def _r(title: str, url: str, kind: str = "docs") -> Resource:
    return Resource(title=title, url=url, kind=kind)


